function deepMerge(base, extra) {
  const out = structuredClone(base);
  for (const [k, v] of Object.entries(extra)) {
    out[k] = typeof v === "object" && v && !Array.isArray(v) ? { ...(out[k] || {}), ...v } : v;
  }
  return out;
}

